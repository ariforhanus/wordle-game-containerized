"""Opt-in real custom-format dump/restore of an owned, queued-mail test fixture.

Never point at production. Requires Docker, Node, PostgreSQL 17 fixture tools and
WORDLE_OUTBOX_RESTORE_CONTAINER, WORDLE_OUTBOX_TEST_KEY_FILE. The source database
is deliberately fixed to wordle_test; a random isolated restore DB is cleaned up.
Key file format is the private env generated by deploy/setup-mail-outbox.mjs.
"""
import base64
import json
import os
from pathlib import Path
import subprocess
import unittest
import uuid

CONTAINER = os.environ.get("WORDLE_OUTBOX_RESTORE_CONTAINER")
KEY_FILE = os.environ.get("WORDLE_OUTBOX_TEST_KEY_FILE")

# Match the Java AAD exactly, including PostgreSQL's microsecond timestamp.
DECRYPT = r"""
const {createDecipheriv,createHash}=require('node:crypto');
let input='';process.stdin.on('data',s=>input+=s).on('end',()=>{
 const {rows,keys}=JSON.parse(input);
 const tokens=rows.map(r=>{
  const [seconds,fraction='']=r.epoch.split('.');
  const aad=[r.key_id,r.id,r.user_id,r.purpose,r.token_hash,seconds+':'+Number(fraction.padEnd(9,'0')),r.message_id].join('|');
  const payload=Buffer.from(r.payload,'base64');
  const cipher=createDecipheriv('aes-256-gcm',Buffer.from(keys[r.key_id],'base64'),Buffer.from(r.nonce,'base64'));
  cipher.setAAD(Buffer.from(aad));cipher.setAuthTag(payload.subarray(-16));
  const data=JSON.parse(Buffer.concat([cipher.update(payload.subarray(0,-16)),cipher.final()]));
  if(createHash('sha256').update(data.token).digest('hex')!==r.token_hash)throw Error('Capability mismatch');
  return data.token;
 });
 process.stdout.write(JSON.stringify(tokens));
});
"""


@unittest.skipUnless(CONTAINER and KEY_FILE, "Requires an owned pending-mail fixture and private test key file")
class MailOutboxRestoreTest(unittest.TestCase):
    def command(self, *args, data=None):
        return subprocess.run(["docker", "exec", "-i", CONTAINER, *args], input=data,
                              capture_output=True, check=True, timeout=45).stdout

    def sql(self, database, query):
        return self.command("psql", "-U", "postgres", "-d", database,
                            "-XAt", "-v", "ON_ERROR_STOP=1", "-c", query).decode().strip()

    def rows(self, database):
        return json.loads(self.sql(database, """
            SELECT coalesce(json_agg(json_build_object(
                'id',id,'user_id',user_id,'purpose',purpose,'token_hash',token_hash,
                'epoch',extract(epoch FROM expires_at)::text,'message_id',message_id,
                'key_id',key_id,'nonce',encode(nonce,'base64'),
                'payload',encode(payload,'base64')) ORDER BY id),'[]'::json)
            FROM mail_outbox WHERE payload IS NOT NULL
        """))

    def test_pending_capabilities_restore_encrypted_and_are_revoked_before_traffic(self):
        content = Path(KEY_FILE).read_text()
        ring = next(line.split("=", 1)[1] for line in content.splitlines()
                    if line.startswith("MAIL_OUTBOX_KEYS="))
        keys = dict(entry.split(":", 1) for entry in ring.split(","))
        self.assertTrue(all(len(base64.b64decode(key, validate=True)) == 32 for key in keys.values()))
        source = self.rows("wordle_test")
        self.assertGreater(len(source), 0, "Fixture must contain live encrypted jobs")
        tokens = json.loads(subprocess.run(["node", "-e", DECRYPT],
                            input=json.dumps({"rows": source, "keys": keys}).encode(),
                            capture_output=True, check=True, timeout=10).stdout)
        archive = self.command("pg_dump", "-U", "postgres", "-d", "wordle_test", "-Fc")
        plain = self.command("pg_restore", "--file=-", data=archive)
        self.assertTrue(all(token.encode() not in plain for token in tokens),
                        "A plaintext delivery capability leaked into the SQL dump")
        target = "wordle_restore_outbox_" + uuid.uuid4().hex[:16]
        self.command("createdb", "-U", "postgres", target)
        try:
            self.command("pg_restore", "-U", "postgres", "--exit-on-error", "--no-owner",
                         "--no-acl", "--dbname=" + target, data=archive)
            restored = self.rows(target)
            self.assertEqual(source, restored, "Encrypted identity/context must survive restore")
            restored_tokens = json.loads(subprocess.run(["node", "-e", DECRYPT],
                                  input=json.dumps({"rows": restored, "keys": keys}).encode(),
                                  capture_output=True, check=True, timeout=10).stdout)
            self.assertTrue(tokens == restored_tokens, "Restore changed delivery capabilities")
            # No worker points to target. Apply the documented recovery-token invalidation.
            self.sql(target, "UPDATE account_tokens SET consumed_at=CURRENT_TIMESTAMP WHERE consumed_at IS NULL")
            self.assertEqual("0", self.sql(target, "SELECT count(*) FROM mail_outbox WHERE payload IS NOT NULL"))
            self.assertEqual("0", self.sql(target, "SELECT count(*) FROM mail_outbox WHERE state IN ('PENDING','PROCESSING','BLOCKED') AND token_hash IS NOT NULL"))
            self.assertEqual(source, self.rows("wordle_test"), "Restore reconciliation changed the source")
        finally:
            self.command("dropdb", "-U", "postgres", target)


if __name__ == "__main__":
    unittest.main()
