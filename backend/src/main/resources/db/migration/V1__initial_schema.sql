CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(64) NOT NULL, email VARCHAR(120) NOT NULL,
 password_hash VARCHAR(100) NOT NULL, created_at TIMESTAMPTZ NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'USER', first_name VARCHAR(64), last_name VARCHAR(64),
 nationality VARCHAR(64), avatar BYTEA, avatar_content_type VARCHAR(64), avatar_size BIGINT,
 CONSTRAINT uk_user_username UNIQUE(username), CONSTRAINT uk_user_email UNIQUE(email)
);
CREATE TABLE IF NOT EXISTS scores (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL, username VARCHAR(20) NOT NULL,
 language VARCHAR(5) NOT NULL, attempts INTEGER NOT NULL,
 duration_ms BIGINT NOT NULL, won_at TIMESTAMPTZ NOT NULL,
 played_at DATE NOT NULL, score INTEGER NOT NULL, word VARCHAR(255), won BOOLEAN NOT NULL DEFAULT TRUE
);
